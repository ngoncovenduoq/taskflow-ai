# 3. Chia van ban thanh cac doan nho
def split_text(
    text: str,
    chunk_size: int = 800,
    overlap: int = 120
) -> list[str]:

    text = text.strip()

    if not text:
        return []

    chunks = []
    start = 0

    while start < len(text):
        end = min(start + chunk_size, len(text))

        chunk = text[start:end]

        if chunk.strip():
            chunks.append(chunk)

        if end == len(text):
            break

        start = end - overlap

    return chunks


def _document_path(document_id: str) -> Path:
    """Accept only IDs generated by uuid4; never use a user-supplied path."""
    if not re.fullmatch(r"[0-9a-f]{32}", document_id):
        raise ValueError("ID tài liệu không hợp lệ.")
    return DOCUMENTS_DIR / f"{document_id}.json"


def get_document(document_id: str) -> dict | None:
    path = _document_path(document_id)
    if not path.is_file():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("document_id") != document_id:
        raise ValueError("Dữ liệu tài liệu không khớp ID.")
    return data


def _indexed_count(document_id: str) -> int:
    result = collection.get(where={"document_id": document_id}, include=["metadatas"])
    return len(result["ids"])


def list_documents() -> list[dict]:
    if not DOCUMENTS_DIR.exists():
        return []
    result = []
    for path in DOCUMENTS_DIR.glob("*.json"):
        if not re.fullmatch(r"[0-9a-f]{32}", path.stem):
            continue
        try:
            data = get_document(path.stem)
            pages = data["pages"]
            expected = sum(len(split_text(str(page.get("text", "")))) for page in pages)
            indexed = _indexed_count(path.stem)
            result.append({
                "document_id": path.stem,
                "filename": data["filename"],
                "total_pages": len(pages),
                "total_characters": sum(len(str(page.get("text", ""))) for page in pages),
                "chunk_count": indexed,
                "indexed": expected > 0 and indexed == expected,
            })
        except (ValueError, KeyError, TypeError, json.JSONDecodeError):
            # Do not silently erase a damaged document; it can be repaired manually.
            continue
    return sorted(result, key=lambda item: item["filename"].casefold())


def index_document(document_id: str) -> int:
    data = get_document(document_id)
    if data is None:
        raise FileNotFoundError("Không tìm thấy tài liệu.")
    ids, documents, metadatas = [], [], []
    for page in data["pages"]:
        page_number = int(page["page"])
        for index, chunk in enumerate(split_text(str(page["text"]))):
            ids.append(f"{document_id}_{page_number}_{index}")
            documents.append(chunk)
            metadatas.append({
                "document_id": document_id,
                "filename": data["filename"],
                "page": page_number,
            })
    if not ids:
        raise ValueError("Tài liệu không có văn bản để lập chỉ mục.")

    existing = set(collection.get(where={"document_id": document_id}, include=["metadatas"])["ids"])
    for start in range(0, len(ids), 50):
        end = start + 50
        collection.upsert(
            ids=ids[start:end],
            documents=documents[start:end],
            metadatas=metadatas[start:end],
        )
    stale = list(existing.difference(ids))
    if stale:
        collection.delete(ids=stale)
    return len(ids)


def delete_document(document_id: str) -> bool:
    path = _document_path(document_id)
    if not path.is_file():
        return False
    indexed_ids = collection.get(where={"document_id": document_id}, include=["metadatas"])["ids"]
    if indexed_ids:
        collection.delete(ids=indexed_ids)
    # Delete only this exact JSON after removing its Chroma entries.
    path.unlink()
    return True


# 4. Doc cac file JSON va tao embeddings
def index_documents() -> int:

    if not DOCUMENTS_DIR.exists():
        print("Chua co thu muc documents.")
        return 0

    total_chunks = 0

    for file_path in DOCUMENTS_DIR.glob("*.json"):

        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        document_id = data["document_id"]
        filename = data["filename"]

        ids = []
        documents = []
        metadatas = []

        for page_data in data["pages"]:

            page_number = page_data["page"]
            page_text = page_data["text"]

            chunks = split_text(page_text)

            for index, chunk in enumerate(chunks):

                chunk_id = (
                    f"{document_id}_"
                    f"{page_number}_{index}"
                )

                ids.append(chunk_id)
                documents.append(chunk)

                metadatas.append({
                    "document_id": document_id,
                    "filename": filename,
                    "page": page_number
                })

        # Luu theo batch de xu ly tai lieu dai
        batch_size = 50

        for start in range(0, len(ids), batch_size):

            end = start + batch_size

            collection.upsert(
                ids=ids[start:end],
                documents=documents[start:end],
                metadatas=metadatas[start:end]
            )

        total_chunks += len(ids)

        print(
            f"Da xu ly {filename}: "
            f"{len(ids)} chunks"
        )

    return total_chunks


# 5. Tim kiem noi dung lien quan
def search_documents(
    question: str,
    top_k: int = 3,
    document_id: str | None = None,
) -> list[dict]:

    if collection.count() == 0:
        return []

    question_lower = question.lower()

    filename = None
    if document_id is not None:
        _document_path(document_id)  # Validate user-controlled ID before the Chroma filter.
    else:
        # Only unscoped questions require scanning document names.
        stored = collection.get(include=["metadatas"])
        filenames = {
            metadata["filename"] for metadata in stored["metadatas"]
            if metadata and metadata.get("filename")
        }
        for name in sorted(filenames, key=len, reverse=True):
            if name.lower() in question_lower:
                filename = name
                break

    # 3. Tao bo loc theo ten PDF
    where_filter = None
    page_offset = 0

    if filename or document_id:
        where_filter = {"document_id": document_id} if document_id else {"filename": filename}

        file_data = collection.get(
            where=where_filter,
            include=["documents", "metadatas"]
        )

        if not file_data["ids"]:
            return []

        if document_id:
            filename = file_data["metadatas"][0]["filename"]

        available_chunks = len(file_data["ids"])

        # Xac dinh trang dau cua tai lieu
        first_page = min(
            int(metadata["page"])
            for metadata in file_data["metadatas"]
        )

        # Chuan hoa so trang neu du lieu bat dau tu 0
        page_offset = 1 if first_page == 0 else 0

        # 4. Xu ly cau hoi ve trang bia
        cover_keywords = [
            "trang bìa",
            "tên đề tài",
            "tên tài liệu",
            "tiêu đề"
        ]

        is_cover_question = any(
            keyword in question_lower
            for keyword in cover_keywords
        )

        if is_cover_question:

            cover_output = []

            for text, metadata in zip(
                file_data["documents"],
                file_data["metadatas"]
            ):

                if int(metadata["page"]) == first_page:

                    cover_output.append({
                        "filename": filename,
                        "page": int(metadata["page"]) + page_offset,
                        "text": text
                    })

                if len(cover_output) >= top_k:
                    break

            if cover_output:
                return cover_output

    else:
        available_chunks = collection.count()

    # 5. Semantic search
    query_args = {
        "query_texts": [question],
        "n_results": min(top_k, available_chunks),
        "include": ["documents", "metadatas"]
    }

    if where_filter:
        query_args["where"] = where_filter

    results = collection.query(**query_args)

    output = []

    documents = results["documents"][0]
    metadatas = results["metadatas"][0]

    for text, metadata in zip(documents, metadatas):

        output.append({
            "filename": metadata["filename"],
            "page": int(metadata["page"]) + page_offset,
            "text": text
        })

    return output


_SEARCH_STOPWORDS = {
    "hay", "cho", "biet", "ve", "so", "sanh", "thong", "tin", "duoc",
    "trinh", "bay", "trong", "giua", "voi", "cac", "cua", "va",
    "pdf", "report", "cv", "tai", "lieu", "ten", "trang", "dan",
    "nguon", "tung", "nhan", "dinh", "nay", "do", "nhung", "nao",
    "the", "hien", "dung", "dua", "tren", "phan", "noi", "den",
}


def _search_terms(text: str) -> list[str]:
    """Normalize Vietnamese keywords without relying on extra packages."""
    normalized = unicodedata.normalize("NFKD", text.lower().replace("đ", "d"))
    normalized = "".join(char for char in normalized if not unicodedata.combining(char))
    return [
        term for term in re.findall(r"[a-z0-9]+", normalized)
        if len(term) >= 2 and term not in _SEARCH_STOPWORDS
    ]


def search_document_hybrid(question: str, document_id: str, top_k: int = 3) -> list[dict]:
    """Combine scoped semantic search with lexical search across a PDF's pages.

    For long comparisons, embeddings can favor the cover or introduction.
    Keyword matches bring back substantive sections without touching the
    user's existing index, while semantic results still cover paraphrases.
    """
    _document_path(document_id)
    if top_k <= 0:
        return []

    # Comparing CV.pdf and Report.pdf is about their contents, not those
    # filename tokens. Keep the topical terms for both retrieval strategies.
    focused = re.sub(r"(?i)\b[\w.-]+\.pdf\b", " ", question)
    focused = re.sub(r"(?i)\bcv\b", " ", focused).strip() or question
    semantic = search_documents(focused, top_k=max(top_k * 3, 6), document_id=document_id)
    indexed = collection.get(
        where={"document_id": document_id},
        include=["documents", "metadatas"],
    )
    if not indexed["ids"]:
        return []
    first_page = min(int(metadata["page"]) for metadata in indexed["metadatas"])
    page_offset = 1 if first_page == 0 else 0

    terms = set(_search_terms(focused))
    if not terms:
        return semantic[:top_k]

    chunk_terms = [set(_search_terms(text)) for text in indexed["documents"]]
    frequency = Counter(term for words in chunk_terms for term in words)
    total = len(chunk_terms)
    lexical = []
    for text, metadata, words in zip(indexed["documents"], indexed["metadatas"], chunk_terms):
        matches = terms.intersection(words)
        if not matches:
            continue
        score = sum(math.log((total + 1) / (frequency[term] + 1)) + 1 for term in matches)
        lexical.append((score, {
            "filename": metadata["filename"],
            "page": int(metadata["page"]) + page_offset,
            "text": text,
        }))
    lexical.sort(key=lambda pair: pair[0], reverse=True)
    lexical_results = [item for _, item in lexical]

    selected = []
    used_chunks = set()
    used_pages = set()

    def add(candidates: list[dict], quota: int, unique_page: bool) -> None:
        for item in candidates:
            if quota <= 0 or len(selected) >= top_k:
                break
            key = (item["page"], item["text"])
            if key in used_chunks or (unique_page and item["page"] in used_pages):
                continue
            selected.append(item)
            used_chunks.add(key)
            used_pages.add(item["page"])
            quota -= 1

    # Favor keyword-relevant pages while retaining a semantic candidate.
    add(lexical_results, max(1, top_k - 1), unique_page=True)
    add(semantic, 1, unique_page=True)
    add(lexical_results + semantic, top_k, unique_page=True)
    add(lexical_results + semantic, top_k, unique_page=False)
    return selected

